export const CURRENCY_CODES: readonly string[] = CURRENCIES.map((c) => c.code);

const BY_CODE = new Map(CURRENCIES.map((c) => [c.code, c]));

export const currencyOf = (code: string | null | undefined): Currency | undefined => (code ? BY_CODE.get(code) : undefined);

/** Запасные курсы для /api/currency: единица USD → единиц валюты */
export const FALLBACK_RATES: Record<string, number> = Object.fromEntries(CURRENCIES.map((c) => [c.code, c.approxRate]));

/**
 * Единая валюта хранения: Expense.amount, бюджеты (Trip.totalBudget, TripMember.budget, BudgetPlan)
 * и Place.budget — всегда в USD (решение владельца 2026-10-22, «модель A»). Формы траты пересчитывают
 * введённую сумму в USD по курсу и хранят исходную в originalAmount/originalCurrency. Trip.currency
 * не выбирается: сервер принимает только USD (POST/PATCH /api/trips, импорт). Настоящая валюта поездки
 * потребует хранения в ней, выбора валюты в UI и пересчёта достижений/профиля — отдельная задача.
 */
export const BASE_CURRENCY = "USD";

/** Символ валюты для UI (бюджет, награды, поиск). */
export function currencySymbol(code: string | undefined | null): string {
  return currencyOf(code)?.sym ?? (code ? `${code} ` : "$");
}

/** Строка в раскрытом списке: человек ищет страну, а код нужен, чтобы сверить с ценником. */
export const currencyLabel = (c: Currency): string => `${c.flag} ${c.country} · ${c.name} (${c.code})`;

/**
 * Разделы списка валют. pinned — валюта группы «Сочтёмся», она всегда сверху. Код вне таблицы
 * (старая трата, снятая с обращения валюта) остаётся в списке: иначе select молча подменил бы его.
 */
export function currencyGroups(current: string, pinned?: string | null): { popular: Currency[]; rest: Currency[] } {
  const known = (code: string): Currency =>
    currencyOf(code) ?? { code, flag: "🏳️", country: code, name: "валюта", approxRate: 0 };
  const head = [pinned, current].filter((c): c is string => !!c).filter((c, i, a) => a.indexOf(c) === i);
  const popular = [...head.filter((c) => pinned === c || !currencyOf(c)).map(known), ...CURRENCIES.slice(0, POPULAR_COUNT)].filter(
    (c, i, a) => a.findIndex((x) => x.code === c.code) === i
  );
  const shown = new Set(popular.map((c) => c.code));
  const rest = CURRENCIES.filter((c) => !shown.has(c.code)).sort((a, b) => a.country.localeCompare(b.country, "ru"));
  return { popular, rest };
}
