function inPolygon(lat: number, lng: number, polygon: readonly Point[]): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [latA, lngA] = polygon[i];
    const [latB, lngB] = polygon[j];
    if (latA > lat !== latB > lat && lng < ((lngB - lngA) * (lat - latA)) / (latB - latA) + lngA) inside = !inside;
  }
  return inside;
}

/** Точка в материковом Китае (без Гонконга, Макао и Тайваня) */
export function inMainlandChina(lat: number, lng: number): boolean {
  return inPolygon(lat, lng, MAINLAND) && !inPolygon(lat, lng, HONG_KONG) && !inPolygon(lat, lng, MACAU);
}
