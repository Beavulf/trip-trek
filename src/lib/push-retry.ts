// Правило ретрая web-push — чистая функция, чтобы покрывалась юнит-тестами
// (сам push-send.ts тянет БД и web-push, его тестировать дорого).

/**
 * Транзиентная ли ошибка доставки: сеть/таймаут приходят БЕЗ statusCode,
 * 429 и 5xx — пуш-сервер перегружен или деградирован (из РФ до Google FCM
 * так и бывает: проба 2026-09-24 — каждый 4-й запрос в таймаут). Прочие
 * 4xx постоянны (кривая подписка, нет прав) — ретрай бессмысленен.
 */
export function shouldRetryPush(statusCode: number | undefined): boolean {
  return statusCode === undefined || statusCode === 429 || statusCode >= 500;
}

/** Пауза перед ретраем: секунды хватает, чтобы перегрузить-не успеть. */
export const PUSH_RETRY_DELAY_MS = 1_000;
