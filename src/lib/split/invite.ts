// Код приглашения: клиентская часть (нормализация ввода). Генерация — invite-server.ts: она тянет node:crypto,
// а этот модуль импортируют клиентские компоненты (webpack не собирает node:-схемы для браузера).

// Кириллица, неотличимая от латиницы на глаз: код, набранный с картинки на русской раскладке, должен сработать
const LOOKALIKES: Record<string, string> = {
  А: "A", В: "B", С: "C", Е: "E", Н: "H", К: "K", М: "M", Р: "P", Т: "T", Х: "X",
};

/** Ввод пользователя → канонический код: пробелы/дефисы убраны, регистр верхний, кириллические двойники → латиница. */
export function normalizeInviteCode(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[\s-]/g, "")
    .replace(/[АВСЕНКМРТХ]/g, (ch) => LOOKALIKES[ch] ?? ch)
    .slice(0, 64);
}
