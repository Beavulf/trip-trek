// Только данные (без React), как onboarding-content.ts: макеты и подписи проверяются тестами.
//
// Как добавить запись: новая — СВЕРХУ списка, id вида `2026-10-26-короткое-имя` (латиница, дефисы),
// date — день выхода. Всем, кто зарегистрировался ДО этого дня, она придёт непрочитанной
// (красный счётчик на колокольчике); новичкам история не показывается (updates.ts).
// У записи — демо из 1–4 экранов: человек сам листает их и видит, как работает новая функция.
// Меняется интерфейс — правьте подписи здесь и в labels: тест сверяет их с исходниками.

import type { StepActionKind } from "./onboarding-content";
import type { MockScene } from "./onboarding-scene";

/** «Центр обучения» открывается только в экране поездки, поэтому в «Сочтёмся» это действие недоступно */
export type UpdateActionKind = StepActionKind | "center";

export type UpdateKind = "new" | "better";
/** Где запись видна: в окне колокольчика поездки, в «Сочтёмся» или в обоих */
export type UpdateArea = "all" | "trip" | "split";

export const UPDATE_KIND_LABEL: Record<UpdateKind, string> = { new: "Новое", better: "Стало лучше" };

export interface UpdateDemoStep {
  /** Что происходит на экране — одной фразой под макетом */
  caption: string;
  scene: MockScene;
}

export interface UpdatePoint {
  icon: string;
  title: string;
  text: string;
}

export interface UpdateEntry {
  id: string;
  /** День выхода, YYYY-MM-DD */
  date: string;
  kind: UpdateKind;
  area: UpdateArea;
  /** Эмодзи на карточке в списке */
  icon: string;
  title: string;
  /** Строка в списке */
  summary: string;
  /** Вступление в открытой записи */
  lead: string;
  /** Для кого запись («Для владельца поездки»); без пометки — для всех */
  audience?: string;
  demo: UpdateDemoStep[];
  points: UpdatePoint[];
  /** Кнопка «Попробовать»: открывает нужное место приложения */
  action?: { label: string; do: UpdateActionKind };
  /** Связанный тур обучения: «Посмотреть тур» */
  tour?: { id: string; label: string };
  /** Подписи интерфейса из текстов записи; тест проверяет, что они есть в исходниках */
  labels?: string[];
}

